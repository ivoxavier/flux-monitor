type LocaleType = typeof locales.pt;

export const getTranslation = (): LocaleType => {
  const browserLang = navigator.language || (navigator as any).userLanguage || 'pt';
  const isEnglish = browserLang.startsWith('en');
  return isEnglish ? locales.en : locales.pt;
};